-- PostgreSQL 14+
-- 在目标数据库内执行，仅用于首次建表，不转换旧版表结构。
-- 当前连接按北京时间显示时间；应用连接同样设置 TimeZone = 'Asia/Shanghai'。

BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    nickname VARCHAR(64) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_username UNIQUE (username)
);

COMMENT ON TABLE users IS '用户';
COMMENT ON COLUMN users.id IS '用户 ID';
COMMENT ON COLUMN users.username IS '唯一用户名，区分大小写';
COMMENT ON COLUMN users.nickname IS '显示昵称';
COMMENT ON COLUMN users.created_at IS '创建时间，按 Asia/Shanghai 显示';

CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL DEFAULT '新对话',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sessions_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_sessions_user_updated ON sessions (user_id, updated_at DESC, id DESC);

COMMENT ON TABLE sessions IS '对话会话';
COMMENT ON COLUMN sessions.id IS '会话 ID';
COMMENT ON COLUMN sessions.user_id IS '所属用户 ID';
COMMENT ON COLUMN sessions.title IS '会话标题';
COMMENT ON COLUMN sessions.created_at IS '创建时间，按 Asia/Shanghai 显示';
COMMENT ON COLUMN sessions.updated_at IS '更新时间，由应用显式更新，按 Asia/Shanghai 显示';

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    reasoning_content TEXT NULL,
    tool_calls JSONB NULL,
    tool_call_id VARCHAR(255) NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_messages_session FOREIGN KEY (session_id)
        REFERENCES sessions (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_messages_role CHECK (role IN ('user', 'assistant', 'tool'))
);

CREATE INDEX idx_messages_session_id ON messages (session_id, id);

COMMENT ON TABLE messages IS '会话消息';
COMMENT ON COLUMN messages.id IS '消息 ID，按 ID 排序读取历史';
COMMENT ON COLUMN messages.session_id IS '所属会话 ID';
COMMENT ON COLUMN messages.role IS 'user / assistant / tool';
COMMENT ON COLUMN messages.content IS '消息正文或工具返回值';
COMMENT ON COLUMN messages.reasoning_content IS '模型显式返回的思考展示文本';
COMMENT ON COLUMN messages.tool_calls IS '助手工具调用数组，无调用时为 NULL';
COMMENT ON COLUMN messages.tool_call_id IS '工具结果对应的调用 ID';
COMMENT ON COLUMN messages.created_at IS '创建时间，按 Asia/Shanghai 显示';

COMMIT;

-- 应用负责校验会话归属、串行处理同一会话请求、校验工具调用与结果配对。
-- 修改会话标题或新增消息时，由应用显式更新 sessions.updated_at = CURRENT_TIMESTAMP。
-- 新增消息与更新会话时间应放在同一事务内。
-- 删除顺序：messages -> sessions -> users，按业务需要在同一事务内执行。
